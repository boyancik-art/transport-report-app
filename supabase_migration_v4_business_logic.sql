on conflict(carrier,month) do nothing;

create table if not exists public.point_tariff_overrides (
 id bigint generated by default as identity primary key,
 route_point_id bigint not null references public.route_points(id) on delete cascade,
 carrier text not null check(carrier in ('STV','SAV')),
 original_zone integer,
 corrected_zone integer check(corrected_zone between 1 and 5),
 calculated_cost numeric(14,2),
 corrected_cost numeric(14,2),
 reason text,
 corrected_by uuid references auth.users(id),
 corrected_at timestamptz not null default now(),
 unique(route_point_id,carrier)
);

create table if not exists public.ts_plus_monthly_costs (
 id bigint generated by default as identity primary key,
 month date not null,
 business text not null,
 amount numeric(14,2) not null,
 created_by uuid references auth.users(id),
 updated_at timestamptz not null default now(),
 unique(month,business)
);

-- Access: authenticated app users can read directories; route editing remains controlled by existing route RLS.
grant select on public.transport_carriers, public.transport_drivers, public.transport_vehicles, public.expeditor_defaults, public.transport_waves, public.extra_point_catalog, public.expeditor_auto_carrier, public.delivery_zones, public.monthly_zone_tariffs to authenticated;
grant select,insert,update on public.route_extra_points to authenticated;
grant select,insert,update on public.point_tariff_overrides, public.ts_plus_monthly_costs to authenticated;
grant usage,select on all sequences in schema public to authenticated;

-- STV/SAV point cost formula used by the app/backend:
-- cost = tt_fixed + (zone_rate * SUM(material_pallets of all documents belonging to one physical TT)).
-- Multiple invoices at one physical TT remain one TT.
